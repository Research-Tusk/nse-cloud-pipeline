function fcModelLabel(m) {
  if (!m) return '—';
  const [fam, hl] = m.split('_hl');
  return (FC_MODEL_LABELS[fam] || fam) + (hl ? ` (half-life ${hl}d)` : '');
}

function fcPct(x, d = 1) {
  if (x == null || isNaN(x)) return '—';
  const v = x * 100;
  return (v > 0.05 ? '+' : v < -0.05 ? '−' : '') + Math.abs(v).toFixed(d) + ' %';
}

function fcEsc(s) {
  return String(s).replace(/[&<>"']/g, c => ({ '&': '&amp;', '<': '&lt;', '>': '&gt;', '"': '&quot;', "'": '&#39;' }[c]));
}

function fcDate(iso) {
  const d = new Date(iso + 'T00:00:00');
  return isNaN(d) ? iso : d.toLocaleDateString('en-IN', { day: '2-digit', month: 'short' });
}

// ── Scenario math (pure functions) ─────────────────────────────

// 45-DMA at T+h when the next h days average `adr` (h ≤ 45)
function fcImpliedMA45(last45, h, adr) {
  const keep = last45.slice(h).reduce((s, r) => s + r.rev, 0);
  return (keep + adr * h) / 45;
}

// 45-DMA at T+h from a daily forecast path scaled by `mult` for the first n days
function fcPathMA45(last45, revHat, h, mult = 1, n = h) {
  const keep = last45.slice(h).reduce((s, r) => s + r.rev, 0);
  let fut = 0;
  for (let j = 0; j < h; j++) fut += revHat[j] * (j < n ? mult : 1);
  return (keep + fut) / 45;
}

function fcRegressionPrice(pm, ma45) {
  if (!pm || pm.status !== 'ok') return null;
  const p = pm.slope * ma45 + pm.intercept;
  const q = pm.resid_q || {};
  return {
    price: p,
    lo80: p + (q.p10 ?? 0), hi80: p + (q.p90 ?? 0),
    lo95: p + (q['p2.5'] ?? 0), hi95: p + (q['p97.5'] ?? 0),
  };
}

function fcRatioPrice(pm, ma45) {
  const r = pm?.ratio?.regression_window;
  if (!r) return null;
  return { price: r.mean * ma45, lo: (r.mean - r.sd) * ma45, hi: (r.mean + r.sd) * ma45 };
}

// PE leg: treat the scenario 45-DMA as the run-rate for the rest of the FY
function fcPEPrice(ex, ma45, cmp) {
  if (typeof computeQuickValuation !== 'function') return null;
  const daily = bseDailySeries(DATA);
  const curFY = currentFYQuarterLabel(new Date()).fy;
  const fyRows = daily.filter(r => r.fy === curFY);
  const a = loadQuickValAssumptions(ex, 0);
  const done = fyRows.length;
  const revToDate = fyRows.reduce((s, r) => s + (r.total_rev || 0), 0);
  const remaining = Math.max(a.tradingDays - done, 0);
  a.adr = a.tradingDays ? (revToDate + ma45 * remaining) / a.tradingDays : ma45;
  const res = computeQuickValuation(ex, a, cmp);
  return { fyAdr: a.adr, eps: res.eps, scenarios: res.scenarios, fy: curFY };
}

function fcRequiredMA45(pm, price) {
  if (!pm || pm.status !== 'ok' || !pm.slope) return null;
  return (price - pm.intercept) / pm.slope;
}

// ── Entry point ────────────────────────────────────────────────

async function buildForecastTab(ex) {
  const el = document.getElementById('forecastContent');
  if (!el) return;
  if (!['nse', 'bse', 'mcx'].includes(ex)) { el.innerHTML = ''; return; }
  el.innerHTML = `<div class="chart-panel" style="text-align:center;padding:40px;color:var(--color-text-muted)">Loading forecast…</div>`;
  try {
    const res = await fetch(`./data/${ex}_forecast.json?t=${Date.now()}`);
    if (!res.ok) throw new Error(res.status);
    FORECAST_DATA = await res.json();
  } catch (e) {
    FORECAST_DATA = null;
    el.innerHTML = `<div class="chart-panel" style="padding:24px;color:var(--color-text-muted)">Forecast data not available yet for ${ex.toUpperCase()} — it is generated by the daily pipeline (scripts/forecast/run.py).</div>`;
    return;
  }
  if (currentExchange !== ex) return; // user switched exchange while loading
  renderForecastTab(el, ex, FORECAST_DATA);
}

