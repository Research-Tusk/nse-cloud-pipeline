function fcSelectionBanner(F) {
  const bt = F.backtest;
  const sel = F.model_selected;
  const best = bt.best_calendar_model;
  const check = (bt.promotion.checks || []).find(c => c.model === best);
  const base = bt.by_model.M1 || {};
  const cov = base.cov80_h20;
  let msg;
  if (sel === 'M1' && check) {
    const g10 = check.mape_gain_h10, g20 = check.mape_gain_h20;
    const p = bt.by_model[best]?.dm_p_h20;
    const gap = g => Math.round(Math.abs(g) * 100) + ' %';
    msg = `<strong>Headline forecast uses the 20-DMA carry baseline.</strong> The ${fcModelLabel(best).toLowerCase()} is ${gap(g10)} / ${gap(g20)} ${g10 >= 0 ? 'more' : 'less'} accurate at 10 / 20 days in the ${bt.test_start} → ${bt.test_end} backtest, but the difference is not yet statistically significant (Diebold–Mariano p = ${p != null ? p.toFixed(2) : '—'}), so it is shown alongside rather than promoted.`;
  } else {
    msg = `<strong>Headline forecast: ${fcModelLabel(sel)}</strong> — passed the promotion rule against the 20-DMA baseline in the ${bt.test_start} → ${bt.test_end} backtest.`;
  }
  return `<div class="chart-panel" style="padding:12px 16px;margin-bottom:var(--space-5);font-size:12px;line-height:1.5;border-left:3px solid var(--color-info)">${msg} Ranges are 80 % / 95 % conformal intervals (baseline backtest coverage at 20 days: ${cov != null ? Math.round(cov * 100) + ' %' : '—'} for the 80 % band).</div>`;
}

