function fcPriceCaveat(pm) {
  if (!pm || pm.status !== 'ok') return '';
  const eg = pm.engle_granger;
  const bits = [];
  if (pm.se_hac && pm.se_ols) bits.push(`slope ${fmtNum(pm.slope, 1)} ± ${fmtNum(pm.se_hac.slope, 1)} (autocorrelation-robust; plain OLS would say ± ${fmtNum(pm.se_ols.slope, 1)})`);
  if (eg) bits.push(eg.cointegrated_5pct
    ? `price and 45-DMA are cointegrated (Engle–Granger p = ${eg.p.toFixed(2)})`
    : `no evidence price and 45-DMA are cointegrated (Engle–Granger p = ${eg.p.toFixed(2)}) — treat the line as a fair-value anchor, not a law`);
  if (pm.mispricing_halflife_days) bits.push(`gaps from the line halve in ~${Math.round(pm.mispricing_halflife_days)} trading days`);
  bits.push(`residual 1σ ${fmtPrice(pm.resid_sd)}`);
  return `<p class="section-desc" style="padding:0 14px 14px;margin:0;font-size:11px">Regression health: ${bits.join(' · ')}. Ranges use the regression's actual residual spread since ${pm.regression_start}.</p>`;
}

