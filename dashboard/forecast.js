function fcRenderPathChart(F) {
  const canvas = document.getElementById('chartFcPath');
  if (!canvas) return;
  if (charts.fcPath) { charts.fcPath.destroy(); delete charts.fcPath; }
  const hist = F.dma.series.slice(-90);
  const p = F.forecast.path;
  const ap = F.alt_forecast?.path;
  const labels = hist.map(r => r.date).concat(p.map(r => r.date));
  const nH = hist.length;
  const pad = n => Array(n).fill(null);
  const lastMA = hist[nH - 1].dma45;
  const fut = key => pad(nH - 1).concat([lastMA], p.map(r => r[key] ?? null));
  setCanvasHeight('chartFcPath', 320);
  charts.fcPath = new Chart(canvas, {
    type: 'line',
    data: {
      labels: labels.map(fcDate),
      datasets: [
        { label: '95 % high', data: fut('hi95'), borderWidth: 0, pointRadius: 0, fill: '+1', backgroundColor: CHART_COLORS[0] + '14' },
        { label: '95 % low', data: fut('lo95'), borderWidth: 0, pointRadius: 0, fill: false },
        { label: '80 % high', data: fut('hi80'), borderWidth: 0, pointRadius: 0, fill: '+1', backgroundColor: CHART_COLORS[0] + '2A' },
        { label: '80 % low', data: fut('lo80'), borderWidth: 0, pointRadius: 0, fill: false },
        { label: 'Daily revenue', data: hist.map(r => r.rev).concat(pad(p.length)), borderColor: CHART_COLORS[5] + '66', backgroundColor: CHART_COLORS[5] + '66', borderWidth: 1, pointRadius: 1.5, tension: 0, showLine: false, hidden: true },
        { label: '5-DMA', data: hist.map(r => r.dma5).concat(pad(p.length)), borderColor: CHART_COLORS[4], borderWidth: 1.2 },
        { label: '20-DMA', data: hist.map(r => r.dma20).concat(pad(p.length)), borderColor: CHART_COLORS[2], borderWidth: 1.5 },
        { label: '45-DMA', data: hist.map(r => r.dma45).concat(pad(p.length)), borderColor: CHART_COLORS[0], borderWidth: 2.2 },
        { label: '45-DMA forecast', data: fut('ma45_hat'), borderColor: CHART_COLORS[0], borderWidth: 2.2, borderDash: [], pointRadius: 2 },
        ...(ap ? [{ label: 'Calendar model', data: pad(nH - 1).concat([lastMA], ap.map(r => r.ma45_hat)), borderColor: CHART_COLORS[3], borderWidth: 1.6, borderDash: [5, 4] }] : []),
      ],
    },
    options: {
      interaction: { mode: 'index', intersect: false },
      plugins: {
        legend: { labels: { filter: it => !/high|low/.test(it.text) } },
        tooltip: {
          filter: it => it.raw != null && !/high|low/.test(it.dataset.label),
          callbacks: { label: c => `${c.dataset.label}: ₹ ${fmtNum(c.raw, 2)} Cr` },
        },
      },
      scales: {
        x: { ticks: { maxTicksLimit: 12, font: { size: 10 } } },
        y: { ticks: { callback: v => '₹' + fmtNum(v, 0), font: { size: 10 } }, title: { display: true, text: '₹ Cr / day', font: { size: 10 } } },
      },
    },
  });
}

