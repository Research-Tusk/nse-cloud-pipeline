function fcVixMetrics(F) {
  const order = ['rev', 'opt_premium', 'contracts', 'io_contracts', 'so_contracts', 'opt_notional', 'pn_bp'];
  return order.filter(m => F.vix.metrics.includes(m));
}

function fcRawFmt(m, v) {
  if (v == null) return '—';
  if (m === 'rev' || m === 'opt_rev') return fmtNum(v, 1);
  if (m.includes('contracts')) return fmtNum(v / 1e6, 1) + ' M';
  if (m === 'pn_bp') return fmtNum(v, 1) + ' bp';
  return fmtNum(v / 1e5, 2) + ' L';   // ₹ Cr → lakh crore
}

function fcRenderVixTable(F, regime, view) {
  const R = F.vix.regimes[regime];
  const box = document.getElementById('fcVixTable');
  if (!R || !box) return;
  const ms = fcVixMetrics(F);
  const head = ms.map(m => `<th style="text-align:right">${FC_METRIC_LABELS[m] || m}${view === 'raw' ? (m === 'rev' ? ' (₹ Cr)' : m.includes('contracts') ? '' : m === 'pn_bp' ? '' : ' (₹ L Cr)') : ''}</th>`).join('');
  const rows = F.vix.buckets_def.filter(b => R.buckets[b]).map(b => {
    const row = R.buckets[b];
    const cur = b === F.vix.current_bucket;
    const cells = ms.map(m => {
      if (view === 'raw') return `<td style="text-align:right">${fcRawFmt(m, row.raw[m])}</td>`;
      const a = row.adj[m];
      if (!a) return '<td style="text-align:right">—</td>';
      const cls = a.rel > 1.005 ? 'positive' : a.rel < 0.995 ? 'negative' : '';
      const ci = a.rel_ci80 ? `<span style="color:var(--color-text-muted);font-size:10px"> [${fcPct(a.rel_ci80[0] - 1, 0)}, ${fcPct(a.rel_ci80[1] - 1, 0)}]</span>` : '';
      return `<td style="text-align:right" class="${cls}">${fcPct(a.rel - 1, 0)}${ci}</td>`;
    }).join('');
    return `<tr style="${cur ? 'outline:2px solid var(--color-primary);outline-offset:-2px' : ''}">
      <td>${b}${row.low_confidence ? ' ◦' : ''}${cur ? ' <strong>← now</strong>' : ''}</td>
      <td style="text-align:right">${row.days}</td>${cells}</tr>`;
  }).join('');
  box.innerHTML = `<table class="data-table"><thead><tr><th>VIX</th><th style="text-align:right">Days</th>${head}</tr></thead><tbody>${rows}</tbody></table>
    <div style="font-size:11px;color:var(--color-text-muted);margin-top:6px">${R.start} → ${R.end} · ${R.days} trading days</div>`;
}

